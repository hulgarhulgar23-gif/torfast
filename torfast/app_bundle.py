def default_install_root() -> Path:
    for candidate in DEFAULT_INSTALL_ROOTS:
        if candidate.is_dir() and os.access(candidate, os.W_OK):
            return candidate
    return DEFAULT_INSTALL_ROOTS[-1]


def install_app(
    *,
    dest_root: Path | None = None,
    python_executable: str | None = None,
    repo_root: Path | None = None,
    version: str = "0.1.0",
    force: bool = False,
    include_summon_service: bool = True,
    services_dir: Path | None = None,
    include_icon: bool = True,
    browser_bin: str | None = None,
) -> dict[str, object]:
    root = Path(dest_root) if dest_root is not None else default_install_root()
    python = python_executable or sys.executable
    resolved_repo_root = Path(repo_root) if repo_root is not None else REPO_ROOT
    app_path = root / f"{APP_NAME}.app"
    report: dict[str, object] = {
        "ok": True,
        "app_path": str(app_path),
        "python": python,
        "repo_root": str(resolved_repo_root),
    }

    if app_path.exists():
        if not force:
            report.update(
                {
                    "ok": False,
                    "reason": f"{app_path} already exists; pass --force to replace it",
                }
            )
            return report
        shutil.rmtree(app_path)

    contents = app_path / "Contents"
    macos_dir = contents / "MacOS"
    resources_dir = contents / "Resources"
    macos_dir.mkdir(parents=True)
    resources_dir.mkdir(parents=True)

    (contents / "Info.plist").write_text(
        INFO_PLIST_TEMPLATE.format(
            identifier=BUNDLE_IDENTIFIER,
            name=APP_NAME,
            version=version,
        ),
        encoding="utf-8",
    )
    browser_env = ""
    if browser_bin:
        browser_env = f'  export TORFAST_BROWSER_BIN="{browser_bin}"'
        report["browser_bin"] = browser_bin
    launcher = macos_dir / "torfast"
    launcher.write_text(
        LAUNCHER_SCRIPT_TEMPLATE.format(
            python=python,
            repo_root=resolved_repo_root,
            browser_env=browser_env,
        ),
        encoding="utf-8",
    )
    launcher.chmod(0o755)

    if include_icon:
        with tempfile.TemporaryDirectory() as work:
            report["icon"] = build_icns(resources_dir / "AppIcon.icns", Path(work))
    else:
        report["icon"] = {"ok": True, "skipped": True, "reason": "disabled"}

    if include_summon_service:
        report["summon_service"] = install_summon_service(
            app_path=app_path,
            services_dir=services_dir,
        )
        report["shortcut_binding_hint"] = SHORTCUT_BINDING_HINT
    else:
        report["summon_service"] = {
            "ok": True,
            "skipped": True,
            "reason": "disabled by flag",
        }
    return report


def install_summon_service(
    *,
    app_path: Path,
    services_dir: Path | None = None,
) -> dict[str, object]:
    target_dir = services_dir if services_dir is not None else SERVICES_DIR
    workflow = target_dir / f"{QUICK_ACTION_NAME}.workflow"
    contents = workflow / "Contents"
    report: dict[str, object] = {"ok": True, "workflow_path": str(workflow)}
    try:
        if workflow.exists():
            shutil.rmtree(workflow)
        contents.mkdir(parents=True)
        (contents / "Info.plist").write_text(
            SERVICE_INFO_PLIST.format(service_name=QUICK_ACTION_NAME),
            encoding="utf-8",
        )
        # The service goes through the app so focus/relaunch behavior stays
        # in one place, and `open` returns immediately so the service never
        # shows as still running.
        command = f'/usr/bin/open "{app_path}"'
        (contents / "document.wflow").write_text(
            SERVICE_DOCUMENT_TEMPLATE.format(command=command),
            encoding="utf-8",
        )
    except OSError as exc:
        report.update({"ok": False, "reason": str(exc)})
    return report
