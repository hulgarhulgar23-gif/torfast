LAUNCHER_SCRIPT_TEMPLATE = """\
#!/bin/zsh
# Generated by `torfast install-app`; regenerate rather than editing.
# Behaves like a normal browser app: click while open focuses the window,
# click while opening is a no-op, otherwise the themed Tor Browser opens
# over the warm managed Tor. The repo root is baked in so torfast imports
# without a pip install.
# the [b]racket trick keeps these patterns from matching any process that
# merely mentions them (including this script and pgrep itself)
BROWSER_PROFILE="{repo_root}/tmp/torfast-browser/browser-profile"
if pgrep -f "[M]acOS/firefox.*$BROWSER_PROFILE" >/dev/null 2>&1; then
  /usr/bin/osascript -e 'tell application "System Events" to set frontmost of (first process whose name is "firefox") to true' >/dev/null 2>&1
  exit 0
fi
if pgrep -f "[-]m torfast open" >/dev/null 2>&1; then
  /usr/bin/osascript -e 'display notification "Already opening — Tor is warming up." with title "Torfast"' >/dev/null 2>&1
  exit 0
fi
/usr/bin/osascript -e 'display notification "Opening the private browser…" with title "Torfast"' >/dev/null 2>&1
LOG="$HOME/Library/Logs/torfast-app.log"
mkdir -p "$HOME/Library/Logs"
(
  cd "{repo_root}" || exit 1
{browser_env}
  "{python}" -m torfast open --json >> "$LOG" 2>&1
  status=$?
  if [ $status -ne 0 ]; then
    /usr/bin/osascript -e "display notification \\"torfast open failed (exit $status) — see torfast-app.log\\" with title \\"Torfast\\"" >/dev/null 2>&1
  fi
) &!
exit 0
"""

